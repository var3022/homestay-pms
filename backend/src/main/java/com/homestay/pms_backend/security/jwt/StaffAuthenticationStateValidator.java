package com.homestay.pms_backend.security.jwt;

import com.homestay.pms_backend.security.AuthenticatedStaffPrincipal;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.dao.EmptyResultDataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import java.sql.Timestamp;
import java.time.Clock;
import java.time.Instant;
import java.util.Map;
import java.util.Optional;
import java.util.UUID;

/**
 * Real-time Staff Security State Validator.
 *
 * Verifies that the staff account backing a validated JWT access token remains:
 * 1. Present in staff_users table.
 * 2. Active (is_active = TRUE).
 * 3. Unlocked (is_locked = FALSE and not under an active timed lockout).
 * 4. Unrevoked (password_changed_at < tokenIssuedAt).
 *
 * Executes authoritative, un-cached queries strictly over the dedicated pms_auth DataSource.
 *
 * ARCHITECTURAL LIMITATIONS & KNOWN CONSTRAINTS:
 * 1. Clock Synchronization:
 *    The token issuance timestamp (iat_millis) is generated by the application server's clock,
 *    whereas password_changed_at is recorded by the PostgreSQL database server (CURRENT_TIMESTAMP).
 *    In clustered or multi-host deployments, clock drift between application nodes and the database
 *    cluster can introduce timestamp skew. Strict NTP synchronization across all hosts is mandatory.
 *
 * 2. Race Conditions & Lack of Token Cache:
 *    Without an active token cache (e.g., Redis revocation blocklist) or a transactional revocation check,
 *    temporal comparisons operate at millisecond resolution. To eliminate ambiguity, equal timestamps
 *    (passwordChangedAt == tokenIssuedAt) fail closed (access rejected). However, we do NOT claim complete
 *    protection against every theoretical distributed race condition without an active token cache or
 *    transactional revocation mechanism.
 *
 * 3. Future Architectural Recommendation (V10+):
 *    To completely eliminate reliance on timestamp comparisons and cross-server clock synchronization,
 *    a future schema migration should add an explicit monotonic integer column:
 *        ALTER TABLE staff_users ADD COLUMN security_version INT NOT NULL DEFAULT 1;
 *    Tokens will carry a 'sec_ver' claim, and any credential mutation or administrative revocation will
 *    increment security_version atomically, allowing integer-equality comparison (token.sec_ver == db.sec_ver).
 */
@Component
@ConditionalOnProperty(prefix = "auth.datasource", name = "enabled", havingValue = "true")
public class StaffAuthenticationStateValidator {

    private static final Logger log = LoggerFactory.getLogger(StaffAuthenticationStateValidator.class);

    private static final String SELECT_ACCOUNT_STATE = """
            SELECT id, email, first_name, last_name, is_active, is_locked, lockout_until, password_changed_at
            FROM staff_users
            WHERE id = ?
            """;

    private final JdbcTemplate authJdbcTemplate;
    private final Clock clock;

    @Autowired
    public StaffAuthenticationStateValidator(
            @Qualifier("authJdbcTemplate") JdbcTemplate authJdbcTemplate,
            Clock clock
    ) {
        this.authJdbcTemplate = authJdbcTemplate;
        this.clock = clock;
    }

    public StaffAuthenticationStateValidator(
            @Qualifier("authJdbcTemplate") JdbcTemplate authJdbcTemplate
    ) {
        this(authJdbcTemplate, Clock.systemUTC());
    }

    /**
     * Checks if the staff account is active, unlocked, and that credentials have not changed
     * at or after the token was issued.
     *
     * @param staffUserId   ID of the staff user
     * @param tokenIssuedAt Issued-at timestamp of the access token (with millisecond precision)
     * @return true if valid and active, false otherwise
     */
    public boolean isAccountStateValid(UUID staffUserId, Instant tokenIssuedAt) {
        if (staffUserId == null || tokenIssuedAt == null) {
            return false;
        }

        Map<String, Object> row;
        try {
            row = authJdbcTemplate.queryForMap(SELECT_ACCOUNT_STATE, staffUserId);
        } catch (EmptyResultDataAccessException e) {
            log.warn("Staff account [{}] does not exist in database. Access token rejected.", staffUserId);
            return false;
        }

        return validateAccountRow(staffUserId, tokenIssuedAt, row);
    }

    /**
     * Revalidates staff account state and constructs verified AuthenticatedStaffPrincipal.
     * Returns empty if staff is missing, inactive, locked, or credentials were changed.
     *
     * @param staffUserId   ID of the staff user
     * @param tokenIssuedAt Issued-at timestamp of the access token
     * @return Optional containing AuthenticatedStaffPrincipal if valid, empty otherwise
     */
    public Optional<AuthenticatedStaffPrincipal> validateAndGetPrincipal(UUID staffUserId, Instant tokenIssuedAt) {
        if (staffUserId == null || tokenIssuedAt == null) {
            return Optional.empty();
        }

        Map<String, Object> row;
        try {
            row = authJdbcTemplate.queryForMap(SELECT_ACCOUNT_STATE, staffUserId);
        } catch (EmptyResultDataAccessException e) {
            log.warn("Staff account [{}] does not exist in database. Access token rejected.", staffUserId);
            return Optional.empty();
        }

        if (!validateAccountRow(staffUserId, tokenIssuedAt, row)) {
            return Optional.empty();
        }

        String email = (String) row.get("email");
        String firstName = (String) row.get("first_name");
        String lastName = (String) row.get("last_name");

        return Optional.of(new AuthenticatedStaffPrincipal(staffUserId, email, firstName, lastName));
    }

    private boolean validateAccountRow(UUID staffUserId, Instant tokenIssuedAt, Map<String, Object> row) {
        // Rule 1: Account must be active
        Boolean isActive = (Boolean) row.get("is_active");
        if (!Boolean.TRUE.equals(isActive)) {
            log.warn("Staff account [{}] is deactivated. Access token rejected.", staffUserId);
            return false;
        }

        // Rule 2: Account must not be locked
        Boolean isLocked = (Boolean) row.get("is_locked");
        Timestamp lockoutUntilTs = (Timestamp) row.get("lockout_until");
        Instant lockoutUntil = lockoutUntilTs != null ? lockoutUntilTs.toInstant() : null;

        if (Boolean.TRUE.equals(isLocked)) {
            if (lockoutUntil == null || lockoutUntil.isAfter(clock.instant())) {
                log.warn("Staff account [{}] is locked (lockout_until: {}). Access token rejected.", staffUserId, lockoutUntil);
                return false;
            }
        } else if (lockoutUntil != null && lockoutUntil.isAfter(clock.instant())) {
            log.warn("Staff account [{}] has active lockout_until {}. Access token rejected.", staffUserId, lockoutUntil);
            return false;
        }

        // Rule 3: Password must have been changed strictly BEFORE the token was issued.
        Timestamp passwordChangedTs = (Timestamp) row.get("password_changed_at");
        // Fail closed on missing, ambiguous, or null password_changed_at
        if (passwordChangedTs == null) {
            log.warn("Staff account [{}] has missing or null password_changed_at timestamp. Fails closed.", staffUserId);
            return false;
        }

        Instant passwordChangedAt = passwordChangedTs.toInstant();

        // Enforce strict temporal invalidation:
        // A password change occurring at or after token issuance revokes the token.
        // Equal or ambiguous timestamps (passwordChangedAt.equals(tokenIssuedAt)) fail closed
        // to prevent race exploitation during simultaneous credential mutation and token issuance.
        // The token is valid ONLY if passwordChangedAt is strictly before tokenIssuedAt.
        if (!passwordChangedAt.isBefore(tokenIssuedAt)) {
            log.warn("Staff account [{}] password changed at {} is not strictly before token issued at {}. Access token revoked.",
                    staffUserId, passwordChangedAt, tokenIssuedAt);
            return false;
        }

        return true;
    }

    /**
     * Validates account state, throwing JwtValidationException if invalid.
     */
    public void validateAccountState(UUID staffUserId, Instant tokenIssuedAt) {
        if (!isAccountStateValid(staffUserId, tokenIssuedAt)) {
            throw new JwtValidationException("Staff account is deactivated, locked, revoked, or no longer exists.");
        }
    }
}
